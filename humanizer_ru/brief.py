"""Сборка задания для LLM: короткая инструкция + находки линтера + текст.

Для тех, у кого нет Claude Code или другого агента со скиллами: команда
`humanizer-ru brief файл.txt` печатает готовый промпт, который можно вставить
в любой чат с моделью. Полная версия инструкции — skills/humanizer-ru/SKILL.md.
"""

from __future__ import annotations

from .linter import Report
from .rules import GENRE_HELP

INSTRUCTION = """Ты редактор русского текста. Задача — сделать текст ниже легко читаемым, не меняя его смысл.
Это не «обход детекторов»: цель — читатель, а не алгоритм.

Правила:
1. Факты неприкосновенны. Числа, даты, имена, названия, версии, ссылки, цитаты — только те, что есть в
   исходнике. Ничего не выдумывать; если для конкретики не хватает данных — оставить пометку [нужны данные].
2. Объективное правь, вкусовое предлагай. Канцелярит, пустые зачины и выводы, штампы, обёртки чат-бота,
   пассив без деятеля, стены текста — правь. Ритм, синонимы, разговорность, метафоры — предлагай отдельным списком.
3. Минимальная достаточная правка. Чистый абзац не трогать. Лучше пропустить дефект, чем испортить живую фразу.
4. Термины остаются. «Проведение документа», «регламентное задание», «обработка», «расширение», СКД, БСП —
   это имена сущностей, а не канцелярит. Не расшифровывать и не заменять, если читатель — коллега.
5. Голос автора важнее правильности: сохраняй его примеры, обороты, позицию, юмор. Не добавляй мнений и
   иронии, которых у автора нет.
6. Лечение по иерархии: удалить → заменить фактом из исходника → сказать проще. Синоним — не лечение:
   «ключевой» → «важнейший» ничего не чинит.
7. Удаляй воду, а не функцию: призыв к действию, ссылка, срок, контакт остаются.
8. Длинное тире, вопросы, списки, повтор термина — нормальный русский язык, не дефект.

Формат ответа:
1) Отредактированный текст — первым блоком, без предисловий.
2) Строка «---».
3) «Что изменено» — 3–7 пунктов.
4) «На решение автора» — вкусовые предложения, которые в текст не внесены.
5) «Нужны данные» — места, где для конкретики не хватило фактов (если есть).
"""


def build_brief(text: str, report: Report, mode: str = "careful", voice: str | None = None) -> str:
    parts = [INSTRUCTION]
    parts.append(f"Жанр: {report.genre} — {GENRE_HELP.get(report.genre, '')}.")
    if mode == "deep":
        parts.append("Режим: deep — можно перестраивать абзацы и порядок аргументов, факты и позиция автора неизменны.")
    else:
        parts.append("Режим: careful — точечные правки, структуру и порядок абзацев не менять.")
    if voice:
        parts.append("")
        parts.append("ПАСПОРТ ГОЛОСА АВТОРА (сильнее общих правил: то, что здесь названо голосом, не править):")
        parts.append(voice.strip())
    if report.findings:
        parts.append("")
        parts.append(f"Находки линтера (оценка {report.score}/100, {report.band}). Это подсказки, не приказ: "
                     "проверяй каждую по контексту.")
        for f in report.findings:
            if f.level == "note":
                continue
            loc = f"стр. {f.line}" if f.line else "текст"
            parts.append(f"- [{f.level}] {loc}: {f.excerpt} → {f.advice}")
    parts.append("")
    parts.append("ТЕКСТ:")
    parts.append("<<<")
    parts.append(text.rstrip())
    parts.append(">>>")
    return "\n".join(parts)
