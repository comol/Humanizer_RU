MONO = " ".join(["Это предложение содержит ровно семь слов подряд."] * 12)
VARIED = ("Коротко. Потом длинное предложение, которое не торопится и объясняет, зачем вообще всё это "
          "затевалось в проекте. Ещё одно короткое. И снова длинное — с оговорками, скобками (вот такими) "
          "и уходом в сторону. Хватит.")


def run() -> int:
    failed = 0
    for text, must, must_not in CASES:
        codes = {f.code for f in lint(text).findings}
        for c in must:
            if c not in codes:
                failed += 1
                print(f"FAIL ожидался [{c}] · {text[:70]!r} · получено {sorted(codes)}")
        for c in must_not:
            if c in codes:
                failed += 1
                print(f"FAIL лишний [{c}] · {text[:70]!r}")
    if "rhythm-flat" not in {f.code for f in lint(MONO).findings}:
        failed += 1
        print("FAIL ожидался [rhythm-flat] на монотонном тексте")
    if "rhythm-flat" in {f.code for f in lint(VARIED).findings}:
        failed += 1
        print("FAIL лишний [rhythm-flat] на рваном тексте")
    # жанр снимает канцелярит
    spec = lint("В целях обеспечения корректности данный документ является обязательным.", "spec")
    if any(f.category in ("bureau", "copula") for f in spec.findings):
        failed += 1
        print("FAIL жанр spec не снял канцелярит")
    # стена текста: в статье порог выше, чем в auto
    para = " ".join(["Абзац растёт слово за словом, и мысль в нём одна."] * 16)  # ~160 слов
    if "wall" not in {f.code for f in lint(para).findings}:
        failed += 1
        print("FAIL ожидался [wall] в auto на абзаце 160 слов")
    if "wall" in {f.code for f in lint(para, "article").findings}:
        failed += 1
        print("FAIL лишний [wall] в article на абзаце 160 слов")
    # экспорт без пустых строк: каждая строка — абзац, стены нет
    export = "\n".join([" ".join(["Строка экспорта из CMS без пустых строк между абзацами тянется."] * 4)] * 5)
    if "wall" in {f.code for f in lint(export).findings}:
        failed += 1
        print("FAIL экспорт «строка = абзац» склеился в стену")
    if failed:
        print(f"\nselftest: {failed} провал(ов)")
        return 1
    print(f"selftest: OK ({len(CASES) + 6} проверок)")
    return 0
