def term_spans(text: str) -> list[tuple[int, int]]:
    return [m.span() for m in TERMS.finditer(text)]


def overlaps(span: tuple[int, int], spans: list[tuple[int, int]]) -> bool:
    a, b = span
    return any(s <= a and b <= e for s, e in spans)
